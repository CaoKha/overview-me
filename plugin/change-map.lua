vim.api.nvim_create_user_command('ChangeMap', function(o)
  require('change-map').load(o.args)
end, { nargs = '?', complete = 'file', desc = 'Load the change map of HEAD (or a map file): quickfix tour + captions' })
vim.api.nvim_create_user_command('ChangeMapPanel', function()
  require('change-map').panel()
end, { desc = 'Open the change map panel' })
vim.api.nvim_create_user_command('ChangeMapDiff', function()
  require('change-map').diff()
end, { desc = 'Diff the current file against the change base' })
vim.api.nvim_create_user_command('ChangeMapOverview', function()
  require('change-map').overview()
end, { desc = 'Open the feature overview of the change map' })
vim.api.nvim_create_user_command('ChangeMapCodebase', function()
  require('change-map').codebase()
end, { desc = 'Open the codebase overview of this repo' })
